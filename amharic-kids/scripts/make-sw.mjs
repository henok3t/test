// After `vite build`: writes dist/sw.js, a service worker that pre-caches every built file
// (app, fonts, audio) so the app works offline once it has been opened.
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const dist = new URL('../dist/', import.meta.url).pathname;
const files = [];
const walk = (d) => readdirSync(d).forEach((f) => {
  const p = join(d, f);
  statSync(p).isDirectory() ? walk(p) : files.push(relative(dist, p));
});
walk(dist);
// only the woff2 fonts are needed by modern browsers; skip the legacy .woff copies
const list = ['./', ...files.filter((f) => f !== 'sw.js' && !f.endsWith('.woff')).map((f) => `./${f}`)];
const hash = createHash('sha1');
for (const f of files) hash.update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 10);

writeFileSync(join(dist, 'sw.js'), `// generated by scripts/make-sw.mjs
const CACHE = 'selam-${version}';
const FILES = ${JSON.stringify(list)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(e.request).then((res) => {
      if (res.ok && new URL(e.request.url).origin === location.origin) {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, copy));
      }
      return res;
    }).catch(() => (e.request.mode === 'navigate' ? caches.match('./') : Response.error())))
  );
});
`);
console.log(`sw.js: ${list.length} files pre-cached (version ${version})`);
